const lit = (v: unknown) => `json.loads(${JSON.stringify(JSON.stringify(v))})`;

export function strategy(t: TypeSpec): string {
  switch (t.t) {
    case 'int':
      return `st.integers(${t.min}, ${t.max})`;
    case 'decimal': {
      const k = 10 ** t.places;
      const ints = `st.integers(${Math.ceil(t.min * k)}, ${Math.floor(t.max * k)})`;
      return t.places ? `${ints}.map(lambda n: n / ${k})` : ints;
    }
    case 'str':
      return `st.text(max_size=${t.max})`;
    case 'bool':
      return 'st.booleans()';
    case 'list':
      return `st.lists(${strategy(t.of)}, max_size=${t.max})`;
    case 'record':
      return `st.fixed_dictionaries({${Object.entries(t.fields).map(([k, v]) => `${JSON.stringify(k)}: ${strategy(v)}`).join(', ')}})`;
    case 'oneof':
      return `st.sampled_from(${lit(t.values)})`;
  }
}

const py = (src: string) => `lambda env: ${expr.toPython(expr.parse(src))}`;

/** A standalone Hypothesis harness (also a valid pytest module) that prints one JSON line per property. */
export function harness(spec: Spec, root: string, opts: { seed: number; runs: number }): string {
  const i = spec.target.lastIndexOf('::');
  const inputs = Object.entries(spec.inputs).map(([k, v]) => `${JSON.stringify(k)}: ${strategy(parseType(v))}`);
  return `# Generated by truthgate for spec ${JSON.stringify(spec.id)}. Do not edit.
import copy, importlib.util, json, os, sys
from hypothesis import given, settings, seed, assume, HealthCheck, strategies as st
${PY_HELPERS}
ROOT = ${JSON.stringify(root)}
FULL = os.path.join(ROOT, ${JSON.stringify(spec.target.slice(0, i))})
sys.path[:0] = [os.path.dirname(FULL), ROOT]
PROTO, sys.stdout = sys.stdout, sys.stderr
_spec = importlib.util.spec_from_file_location("truthgate_target", FULL)
_mod = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(_mod)
TARGET = getattr(_mod, ${JSON.stringify(spec.target.slice(i + 2))})
INPUT = st.fixed_dictionaries({${inputs.join(', ')}})
REQS = [${spec.requires.map(py).join(', ')}]
PROPS = [${spec.ensures.map((p) => `(${JSON.stringify(p.name)}, ${py(p.expr)})`).join(', ')}]
ALLOW_CRASH = ${spec.allowCrash ? 'True' : 'False'}

def show(v):
    s = json.dumps(v)
    return s[:300] + "..." if len(s) > 300 else s

def check(name, prop):
    r = {"name": name, "runs": 0, "skips": 0}

    @seed(${opts.seed})
    @settings(max_examples=${opts.runs}, deadline=None, database=None, suppress_health_check=list(HealthCheck))
    @given(INPUT)
    def test(inp):
        if "abort" in r:
            return
        try:
            pre = all(_bool(q(dict(inp))) for q in REQS)
        except Exception as e:
            r["abort"] = f"expression error: {e}"
            return
        if not pre:
            r["skips"] += 1
            assume(False)
        try:
            raw = TARGET(*copy.deepcopy(list(inp.values())))
        except Exception as e:
            if isinstance(e, ValueError) or type(e).__name__ == "Rejected" or ALLOW_CRASH:
                r["skips"] += 1
                assume(False)
            r.update(ce=inp, why=f"crash for {show(inp)}: {type(e).__name__}: {e}")
            raise
        try:
            out = json.loads(json.dumps(raw, allow_nan=False))
        except (ValueError, TypeError) as e:
            r.update(ce=inp, why=f"crash for {show(inp)}: unserialisable output: {e}")
            raise AssertionError(r["why"])
        r["runs"] += 1
        try:
            ok, err = _bool(prop({**inp, "out": out})), ""
        except ExprCostError as e:
            # too expensive to evaluate says nothing about the code: UNVERIFIED, never FALSIFIED
            r["abort"] = f"expression error: {e}"
            return
        except Exception as e:
            # requires held, so an error here comes from the output: a failure, not a dodge
            ok, err = False, f" (expression error: {e})"
        if not ok:
            r.update(ce=inp, why=f"{name} failed for {show(inp)}: out = {show(out)}{err}")
            raise AssertionError(r["why"])

    try:
        test()
        r["status"] = "ok"
    except Exception as e:
        r["status"] = "fail" if "why" in r else "error"
        r.setdefault("why", f"{type(e).__name__}: {e}")
    return r

def test_all():
    for name, prop in PROPS:
        PROTO.write("TRUTHGATE " + json.dumps(check(name, prop)) + "\\n")
        PROTO.flush()

if __name__ == "__main__":
    test_all()
`;
}

type Line = { name: string; status: 'ok' | 'fail' | 'error'; runs: number; skips: number; ce?: unknown; why?: string; abort?: string };

/** Native path for Python function specs. Returns verdicts, or a reason string when setup failed (caller falls back to the shim). */
export async function runHypothesis(spec: Spec, root: string, opts: RunOptions): Promise<Verdict[] | string> {
  const t0 = Date.now();
  let script: string;
  try {
    script = harness(spec, root, opts);
  } catch (e) {
    return `harness generation failed: ${(e as Error).message}`;
  }
  const dir = await mkdtemp(join(tmpdir(), 'truthgate-hyp-'));
  try {
    const file = join(dir, `test_truthgate_${spec.id.replace(/\W/g, '_')}.py`);
    await writeFile(file, script);
    const r = await exec([...pythonCmd(root), file], { cwd: root, env: pythonEnv(), timeoutMs: Math.max(1, opts.deadline - Date.now()) });
    const lines = r.stdout
      .split('\n')
      .filter((l) => l.startsWith('TRUTHGATE '))
      .map((l) => JSON.parse(l.slice(10)) as Line);
    if (!lines.length && !r.error?.startsWith('timed out')) {
      const tail = (r.error ?? r.stderr).trim().split('\n').at(-1)?.trim();
      return tail || `exit ${r.code}`;
    }
    const byName = new Map(lines.map((l) => [l.name, l]));
    return spec.ensures.map((p): Verdict => {
      const base = { specId: spec.id, property: p.name, seed: opts.seed, durationMs: Date.now() - t0 };
      const l = byName.get(p.name);
      if (!l) return { ...base, kind: 'UNVERIFIED', detail: 'timeout (Hypothesis run did not finish)' };
      const v = (kind: Verdict['kind'], detail: string): Verdict => ({ ...base, runs: l.runs, kind, detail });
      if (l.status === 'fail') return { ...v('FALSIFIED', l.why!), counterexample: l.ce };
      if (l.abort) return v('UNVERIFIED', `${l.abort} (after ${l.runs} runs)`);
      if (l.status === 'error') return v('UNVERIFIED', `Hypothesis error: ${l.why}`);
      if (l.skips > l.runs) return v('UNVERIFIED', `preconditions too strict: ${l.skips} inputs discarded vs ${l.runs} run`);
      if (!l.runs) return v('UNVERIFIED', 'no inputs were run');
      return v('TESTED', `${l.runs} runs, 0 failures: failure rate < 3/${l.runs} (95%) [Hypothesis]${l.skips ? `; ${l.skips} inputs discarded by requires/rejected` : ''}`);
    });
  } finally {
    await rm(dir, { recursive: true, force: true });
  }
}
